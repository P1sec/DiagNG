    def update_decoding_progress(
        self,
        num_entry: int,
        total_entries: int,
    ):
        if total_entries > 1:
            if not self.decoding_in_progress:
                self.decoding_in_progress = True

                def on_close(
                    alert_dialog: Adw.AlertDialog, result: Gio.AsyncResult
                ):
                    try:
                        alert_dialog.choose_finish(result)
                    except Exception:
                        pass
                    self.decoding_in_progress = False

                    alert_dialog.force_close()

                    if self.progress_status:
                        self.progress_status.cancel()
                        self.progress_status = None

                self.progress_dialog.choose(
                    self, self.progress_status, on_close
                )
            self.progress_gauge.set_fraction(num_entry / total_entries)
            if self.progress_status and num_entry >= total_entries:
                self.decoding_in_progress = False
                self.progress_status.cancel()
                self.progress_status = None

    @Gtk.Template.Callback()
    def start_ws_capture_clicked(self, target: Gtk.Button, *args):

        def do_spawn(*args):
            # Spawn wireshark pipe, with flatpak-spawn if needed

            self.create_wireshark_pipe()

        if not self.offline_mode:
            # Enable network-related logs, if this is a live device

            self.log_manager.register_ota_related_logs(do_spawn)

            self.start_ws_capture_button.set_visible(False)
            self.stop_ws_capture_button.set_visible(True)
            self.ws_capture_row.set_activatable_widget(
                self.stop_ws_capture_button
            )
        else:
            # Just spawn Wireshark if this is a DLF file

            do_spawn()

