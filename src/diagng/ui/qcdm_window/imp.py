    def stop_ws_capture_clicked(self, target: Gtk.Button, *args):
        if self.wireshark_instance:
            self.wireshark_instance.close()
            self.wireshark_instance = None

    @Gtk.Template.Callback()
    def pick_pcap_file_clicked(self, target: Gtk.Button, *args):
        # Enable network-related logs

        def file_picked(file_dialog: Gtk.FileDialog, task: Gio.Task):

            try:
                open_result: Gio.File = file_dialog.save_finish(task)
            except GLib.GError as err:
                if err.message != 'Dismissed by user':
                    dialog = Adw.AlertDialog.new(
                        'Could not open file', err.message
                    )
                    dialog.add_response('ok', 'Ok')
                    dialog.set_default_response('ok')
                    dialog.set_close_response('ok')
                    dialog.choose(self, None, None)
                return

            # - Launch the file-based capture in another task
            # - Switch the trigger button to a "Stop capture" button
            #   (with dangerous/red styling?) when a capture to
            #   a PCAP file is active

            def do_open(*args):
                file_path = open_result.get_path()

                visible_file_path = file_path
                if visible_file_path.startswith(
                    '/run/user'
                ):  # Flatpak-sandboxed path
                    visible_file_path = visible_file_path.split('/').pop()

                self.pcap_capture_row.set_subtitle(
                    'Writing to: ' + visible_file_path
                )

                self.create_pcap_pipe(open_result)

            if not self.offline_mode:
                # Enable network-related logs, if this is a live device

                self.log_manager.register_ota_related_logs(do_open)

                self.pick_pcap_file_button.set_visible(False)
                self.stop_pcap_capture_button.set_visible(True)
                self.pcap_capture_row.set_activatable_widget(
                    self.stop_pcap_capture_button
                )
            else:
                # Just spawn Wireshark if this is a DLF file

                do_open()

        file_picker = Gtk.FileDialog()
        file_picker.set_initial_name('output_file.pcap')
        file_picker.save(self, callback=file_picked)

    @Gtk.Template.Callback()
    def stop_pcap_capture_clicked(self, target: Gtk.Button, *args):
        if self.output_pcap:
            self.output_pcap.close()
            self.output_pcap = None

    def create_pcap_pipe(self, output_file: Gio.File):
        assert not self.output_pcap

        self.output_pcap = PcapOutput(
            mode_selector=InteractiveGUIFileOutModeSelector(output_file, self),
            output_file=output_file,
        )

        def on_stream_closed(*args):
            self.pick_pcap_file_button.set_visible(True)
            self.stop_pcap_capture_button.set_visible(False)
            self.pcap_capture_row.set_activatable_widget(
                self.pick_pcap_file_button
            )
            self.pcap_capture_row.set_subtitle('')

            self.output_pcap = None

            if self.pcap_ota_decoder:
                self.pcap_ota_decoder.disconnect()
                self.pcap_ota_decoder = None

        def on_stream_available(*args):
            # Transmit on-the-fly converted ota rrc gsmtap v3 pcap -
            #   use adapter classes for data conversion
            self.pcap_ota_decoder = OTADecoder(
                self.output_pcap,
                self.input_obj,
                self.enable_raw_qcdiag_switch.get_active(),
            )
            self.enable_raw_qcdiag_switch.bind_property(
                'active', self.pcap_ota_decoder, 'embed_raw_qcdiag'
            )

            def close_wireshark(*args):
                if self.output_pcap:
                    self.output_pcap.close()
                    self.output_pcap = None

            self.input_obj.closed.connect(close_wireshark)

            # If this is a DLF or QMDL file, process data
            self.progress_status = Gio.Cancellable.new()
            self.input_obj.process_stream(self.progress_status)

        self.output_pcap.stream_closed.connect(on_stream_closed)

        self.output_pcap.stream_active.connect(on_stream_available)
        self.output_pcap.open_stream()

    def create_wireshark_pipe(self):
        assert not self.wireshark_instance

        self.wireshark_instance = PcapOutput(use_wireshark=True)

        def on_stream_closed(*args):
            self.start_ws_capture_button.set_visible(True)
            self.stop_ws_capture_button.set_visible(False)
            self.ws_capture_row.set_activatable_widget(
                self.start_ws_capture_button
            )

            self.wireshark_instance = None

            if self.ws_ota_decoder:
                self.ws_ota_decoder.disconnect()
                self.ws_ota_decoder = None

        def on_stream_available(*args):
            # Transmit on-the-fly converted ota rrc gsmtap v3 pcap -
            #   use adapter classes for data conversion
            self.ws_ota_decoder = OTADecoder(
                self.wireshark_instance,
                self.input_obj,
                self.enable_raw_qcdiag_switch.get_active(),
            )
            self.enable_raw_qcdiag_switch.bind_property(
                'active', self.ws_ota_decoder, 'embed_raw_qcdiag'
            )

            def close_wireshark(*args):
                if self.wireshark_instance:
                    self.wireshark_instance.close()
                    self.wireshark_instance = None

            self.input_obj.closed.connect(close_wireshark)

            # If this is a DLF or QMDL file, process data
            self.progress_status = Gio.Cancellable.new()
            self.input_obj.process_stream(self.progress_status)

        self.wireshark_instance.stream_closed.connect(on_stream_closed)

        self.wireshark_instance.stream_active.connect(on_stream_available)
        self.wireshark_instance.open_stream()

    def on_title_change(self, *args):
        self.set_title(self.input_obj.full_name)

    def on_state_change(self, *args):
        if not isinstance(self.input_obj, DLFInput):
            self.qcdm_stack.set_sensitive(
                self.input_obj.state == InputState.Processing
            )

        self.parent.update_serial_modems()

    def on_quit(self, *args):
        self.input_obj.close()

        if self.plugin_watch_task:
            self.plugin_watch_task.cancel()
            self.plugin_watch_task = None

