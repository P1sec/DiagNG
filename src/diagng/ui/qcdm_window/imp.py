    def gather_wireshark_info(self):
        def on_version(version: Optional[str]):
            if not version:
                self.wireshark_version_label.set_text('(Unavailable ⚠️)')
                self.start_ws_capture_button.set_sensitive(False)
                # (⚠️ Maybe display/add extra download instructions?)
            else:
                self.wireshark_version_label.set_text(version)
                self.start_ws_capture_button.set_sensitive(True)

        PcapOutput.check_wireshark_version(on_version)

    def gather_device_info(self):
        # Use self.input_obj to display Diag-related
        # info in the first tab of QCDMWindow
        #
        # For this, send a write command to the DBus
        # daemon

        payload = DiagVernoFReq()
        payload._check()

        diag_request = DiagRequest()
        diag_request.cmd_code = DiagCmd.verno_f
        diag_request.payload = payload
        diag_request._check()

        def req_cb(response: DiagResponse):
            info('DiagResponse received for DiagCmd.verno_f: %r' % response)

            # ⚠️ TODO ➡️ Add due error HANDLING Here?

            pretty_info = pretty_print_struct(response)
            self.device_info_buffer.set_text(pretty_info)

            # => Next step:
            #   Clear all logs before getting log support info

            self.disable_logs()

        self.input_obj.send_recv(
            diag_request, req_cb, accept_error=True, retry=True, retry_delay=2
        )
